export type LegalDocKey = keyof typeof DOCS

interface LegalDocProps {
  doc: LegalDocKey
}

export default function LegalDoc({ doc }: LegalDocProps) {
  const content = DOCS[doc]
  const lead = 'lead' in content ? content.lead : undefined

  return (
    <article className={styles.page}>
      <header className={styles.head}>
        <h1>{content.title}</h1>
        <p>시행일 {LEGAL.effectiveDate}</p>
      </header>

      {lead && <p className={styles.lead}>{lead}</p>}

      {content.articles.map((article: Article) => (
        <section key={article.heading} className={styles.article}>
          {article.chapter && <p className={styles.chapter}>{article.chapter}</p>}
          <h2>{article.heading}</h2>

          {article.paragraphs?.map((text) => (
            <p key={text}>{text}</p>
          ))}

          {article.table && (
            // 좁은 화면에서 표가 카드 밖으로 넘치지 않게 표만 따로 가로 스크롤합니다.
            <div className={styles.tableWrap}>
              <table className={styles.table}>
                <thead>
                  <tr>
                    {article.table.head.map((cell) => (
                      <th key={cell}>{cell}</th>
                    ))}
                  </tr>
                </thead>
                <tbody>
                  {article.table.rows.map(([label, value]) => (
                    <tr key={label}>
                      <th scope="row">{label}</th>
                      <td>{value}</td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}

          {article.list &&
            (article.list.ordered ? (
              <ol className={styles.ordered}>
                {article.list.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ol>
            ) : (
              <ul className={styles.bullets}>
                {article.list.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ul>
            ))}

          {article.note && <p className={styles.note}>{article.note}</p>}
        </section>
      ))}
    </article>
  )
}
