-- 상품의 기존 메모 값을 규격으로 옮긴다.
--
-- 20260908_0025 로 spec(규격)을 더할 때는 기존 memo 값을 비고로 남길 생각이었다.
-- 실제 값("표준 프로브", "교체 부품 100", "상급종합 대상 상위 모델")을 보면 전부 제품
-- 규격이라 규격 자리로 옮기고, 비고(memo)는 비워 새로 적게 한다.
--
-- 0025 직후라 spec 은 전부 NULL 이다. 덮어쓰는 값이 없다.
-- 아직 물러나지 않은 구코드는 이 값을 "메모"로 보여 주고 있었으므로, 적용 뒤 배포 전까지
-- 구코드 화면에서는 메모 칸이 비어 보인다. 오류가 아니라 빈 값이다.

BEGIN;

UPDATE public.product
SET spec = memo,
    memo = NULL
WHERE memo IS NOT NULL;

COMMIT;
